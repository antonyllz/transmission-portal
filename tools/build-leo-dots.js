/* run from the portal root with world-atlas countries-50m.json downloaded next to it; writes map-dots.js (move it to leo/) */
/* Builds leo/map-dots.js: a dot matrix of the land around the Amazon Leo sites
   (Brazil + neighbours) from Natural Earth 1:50m (world-atlas). */
const fs = require('fs');
const topo = JSON.parse(fs.readFileSync('countries-50m.json', 'utf8'));
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => { let x = 0, y = 0; return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]]; }); });
const ring = (ids) => { const out = []; ids.forEach((i) => { const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i]; a.forEach((p, k) => { if (k || !out.length) out.push(p); }); }); return out; };
const geoms = topo.objects.countries.geometries;
const polys = [];
geoms.forEach((g) => {
  const list = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
  list.forEach((p) => polys.push({ id: g.id, name: (g.properties || {}).name, rings: p.map(ring) }));
});
const inRing = (x, y, r) => { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c; } return c; };
const inPoly = (x, y, p) => inRing(x, y, p.rings[0]) && !p.rings.slice(1).some((h) => inRing(x, y, h));
/* view box around the sites (Ocara, Sanharó, Rio, Barueri) */
const B = { w: -50.5, e: -33.2, s: -25.6, n: -1.6 }, step = 0.24;
const cand = polys.filter((p) => p.rings[0].some(([x, y]) => x > B.w - 5 && x < B.e + 5 && y > B.s - 5 && y < B.n + 5));
const dots = [];
for (let lat = B.n; lat >= B.s; lat -= step) {
  for (let lng = B.w; lng <= B.e; lng += step / Math.cos(lat * Math.PI / 180)) {
    const p = cand.find((q) => inPoly(lng, lat, q));
    if (p) dots.push([+lng.toFixed(2), +lat.toFixed(2), p.id === '076' ? 1 : 0]);
  }
}
const js = '/* Dot matrix of the land around the Amazon Leo sites — Natural Earth 1:50m via world-atlas.\n   [lng, lat, isBrazil]. Generated by tools (mkdots); bounds: ' + JSON.stringify(B) + ' */\nvar LEO_DOTS = ' + JSON.stringify(dots) + ';\nvar LEO_BOUNDS = ' + JSON.stringify(B) + ';\n';
fs.writeFileSync('map-dots.js', js);
console.log(dots.length, 'dots,', dots.filter((d) => d[2]).length, 'in Brazil,', (js.length / 1024).toFixed(1) + ' KB; countries:', [...new Set(cand.map((p) => p.name))].join(', '));
